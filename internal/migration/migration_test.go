type fixtureGoRunner struct {
	packageError string
	getCalls     int
}

func (runner *fixtureGoRunner) Run(ctx context.Context, directory string, args ...string) ([]byte, error) {
	if runner.packageError != "" && len(args) > 0 && args[0] == "list" {
		return []byte(fmt.Sprintf(
			`{"ImportPath":"example.com/app","Incomplete":true,"Error":{"Err":%q}}`,
			runner.packageError,
		)), nil
	}

	if len(args) == 0 || args[0] != "get" {
		return (execGoRunner{}).Run(ctx, directory, args...)
	}

	runner.getCalls++
	if len(args) != 3 || !strings.HasPrefix(args[1], "-modfile=") {
		return nil, fmt.Errorf("unexpected go get arguments: %q", args)
	}

	modPath := strings.TrimPrefix(args[1], "-modfile=")
	queryAt := strings.LastIndex(args[2], "@")
	if queryAt < 0 {
		return nil, fmt.Errorf("dependency query does not include a version: %q", args[2])
	}
	version := args[2][queryAt+1:]

	data, err := os.ReadFile(modPath)
	if err != nil {
		return nil, err
	}
	file, err := modfile.Parse(modPath, data, nil)
	if err != nil {
		return nil, err
	}
	setMigrationRequirements(file, version, false)
	file.Cleanup()
	formatted, err := file.Format()
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(modPath, formatted, 0o644); err != nil {
		return nil, err
	}

	sumPath := strings.TrimSuffix(modPath, ".mod") + ".sum"
	sumLine := fmt.Sprintf(
		"%s %s h1:iuizFAAo2rQ26HWisB0qtsP5rxJ45bHH6qBr14TyUUU=\n"+
			"%s %s/go.mod h1:IjoBKZuRggOvP+beDB4FPosw2NAq/EYabdaHpUVtfmY=\n",
		v2ModulePath,
		version,
		v2ModulePath,
		version,
	)
	existing, err := os.ReadFile(sumPath)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return nil, err
	}
	if !bytes.Contains(existing, []byte(sumLine)) {
		existing = append(existing, sumLine...)
	}
	if err := os.WriteFile(sumPath, existing, 0o644); err != nil {
		return nil, err
	}

	return nil, nil
}

