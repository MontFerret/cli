const fixtureFerretVersion = "v2.0.0-alpha.44"

func TestMigratorRewritesEverySupportedCompatibilityImport(t *testing.T) {
	root := writeMigrationFixture(t, `module example.com/app

go 1.25.0

require github.com/MontFerret/ferret v1.0.0
`, map[string]string{
		"main.go": `// Package app keeps this comment.
package app

import (
	"fmt"

	"github.com/MontFerret/ferret"
	"github.com/MontFerret/ferret/pkg/compiler"
	_ "github.com/MontFerret/ferret/pkg/runtime"
	. "github.com/MontFerret/ferret/pkg/runtime/core"
	values "github.com/MontFerret/ferret/pkg/runtime/values"
	"github.com/MontFerret/ferret/pkg/runtime/values/types"
)

var _ = fmt.Sprintf
`,
	})

	migrator, runner := newFixtureMigrator()
	result, err := migrator.Migrate(context.Background(), Options{Directory: root})
	if err != nil {
		t.Fatal(err)
	}

	if !result.Applied || result.UpdatedImports != 6 || result.FormattedFiles != 1 {
		t.Fatalf("unexpected result: %#v", result)
	}
	if runner.getCalls != 1 {
		t.Fatalf("expected one dependency resolution, got %d", runner.getCalls)
	}

	source := readMigrationFixture(t, filepath.Join(root, "main.go"))
	for _, expected := range []string{
		`ferret "github.com/MontFerret/ferret/v2/compat"`,
		`"github.com/MontFerret/ferret/v2/compat/compiler"`,
		`_ "github.com/MontFerret/ferret/v2/compat/runtime"`,
		`. "github.com/MontFerret/ferret/v2/compat/runtime/core"`,
		`values "github.com/MontFerret/ferret/v2/compat/runtime/values"`,
		`"github.com/MontFerret/ferret/v2/compat/runtime/values/types"`,
		`// Package app keeps this comment.`,
		`"fmt"`,
	} {
		if !strings.Contains(source, expected) {
			t.Fatalf("expected migrated source to contain %q:\n%s", expected, source)
		}
	}

	parsed := parseMigrationFixtureMod(t, root)
	if version, _ := migrationRequirement(parsed, v1ModulePath); version != "" {
		t.Fatalf("expected v1 requirement to be removed, got %s", version)
	}
	if version, indirect := migrationRequirement(parsed, v2ModulePath); version != fixtureFerretVersion || indirect {
		t.Fatalf("unexpected v2 requirement: version=%q indirect=%v", version, indirect)
	}
	if sum := readMigrationFixture(t, filepath.Join(root, "go.sum")); !strings.Contains(sum, v2ModulePath+" "+fixtureFerretVersion) {
		t.Fatalf("expected v2 checksums, got:\n%s", sum)
	}
}

