func TestCommitMigrationChangesRollsBackEarlierFiles(t *testing.T) {
	root := t.TempDir()
	firstPath := filepath.Join(root, "first.go")
	secondPath := filepath.Join(root, "query.fql")
	if err := os.WriteFile(firstPath, []byte("first-before"), 0o640); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(secondPath, []byte("second-before"), 0o600); err != nil {
		t.Fatal(err)
	}

	first := mustMigrationSnapshot(t, firstPath)
	second := mustMigrationSnapshot(t, secondPath)
	changes := []plannedChange{
		{
			change: Change{Path: "first.go", Before: first.Data, After: []byte("first-after"), BeforeExists: true},
			before: first,
			mode:   first.Mode,
		},
		{
			change: Change{Path: "query.fql", Before: second.Data, After: []byte("second-after"), BeforeExists: true},
			before: second,
			mode:   second.Mode,
		},
	}

	originalRename := renameMigrationFile
	calls := 0
	renameMigrationFile = func(oldPath, newPath string) error {
		calls++
		if calls == 2 {
			return errors.New("replacement failed")
		}

		return os.Rename(oldPath, newPath)
	}
	t.Cleanup(func() { renameMigrationFile = originalRename })

	if err := commitMigrationChanges(changes); err == nil || !strings.Contains(err.Error(), "replacement failed") {
		t.Fatalf("unexpected error: %v", err)
	}
	if got := readMigrationFixture(t, firstPath); got != "first-before" {
		t.Fatalf("first file was not rolled back: %q", got)
	}
	if got := readMigrationFixture(t, secondPath); got != "second-before" {
		t.Fatalf("second file changed: %q", got)
	}
}

