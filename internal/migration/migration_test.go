func snapshotMigrationFixture(t *testing.T, root string) map[string][]byte {
	t.Helper()

	result := make(map[string][]byte)
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}

		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		result[filepath.ToSlash(relative)] = data

		return nil
	})
	if err != nil {
		t.Fatal(err)
	}

	return result
}

func assertMigrationFixtureUnchanged(t *testing.T, root string, before map[string][]byte) {
	t.Helper()

	after := snapshotMigrationFixture(t, root)
	if len(after) != len(before) {
		t.Fatalf("fixture file count changed: before=%d after=%d", len(before), len(after))
	}

	paths := make([]string, 0, len(before))
	for path := range before {
		paths = append(paths, path)
	}
	sort.Strings(paths)

	for _, path := range paths {
		if !bytes.Equal(before[path], after[path]) {
			t.Fatalf("%s changed:\nbefore:\n%s\nafter:\n%s", path, before[path], after[path])
		}
	}
}

